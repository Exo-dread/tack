    private static LauncherSession Open(IReadOnlyList<Display>? ds = null, LauncherConfig? config = null)
    {
        var s = Session(config, displays: ds);
        s.Begin(s.Scene.Orb, 0);
        s.Release(s.Scene.Orb, 80);
