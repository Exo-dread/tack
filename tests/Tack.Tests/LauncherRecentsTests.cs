    }

    private static SessionResult Click(LauncherSession s, PxPoint p, long t = 100)
    {
        s.Move(p, t);
        s.PointerDown(p);
        return s.PointerUp(p);
    }

    private static void ClickMode()
    {
        var ds = new[] { Main, Left };
        var s = Open(ds);
        s.Move(At(s, 1), 1000);
        s.Tick(1000 + LauncherSession.ClickDwellMs - 50);
        Check.True(s.Recents == null, "not before the rest");
        s.Tick(1000 + LauncherSession.ClickDwellMs + 1);
        Check.Equal(RevitNode, s.Recents ?? new NodeRef(-1), "resting on Revit shows its recent files");

        // Hovering another shortcut on the way doesn't put them away; clicking a file opens it.
        s.Move(At(s, 2), 1700);
        Check.True(s.Recents == RevitNode, "hovering a neighbour keeps them (with clicks)");
        var box = s.Scene.RecentsBox(RevitNode);
        Check.Equal(SessionResult.Nothing, Click(s, new PxPoint(box.X + box.Width / 2, box.Y + 3), 1800), "clicking the caption does nothing");
        Check.Equal(SessionMode.Click, s.Mode, "still open");
        var r = Click(s, s.Scene.RecentRows(RevitNode)[4].Center, 1900);
        Check.True(r.Outcome == Outcome.Launch && r.Launch!.Entry.Document == RevitFiles[4], "clicking a file opens it");

        var p = Open(ds);
        p.SecondaryClick(At(p, 1));
        Check.True(p.Selector == RevitNode && p.Recents == null, "right-click Revit: the display picker, as before");
        var tile = p.Scene.TilesFor(RevitNode)[1];
        Check.True(Click(p, tile.Center).Launch is { Display: 1, Entry.Document: null }, "a display: Revit opens there");

        // Resting on Revit with its files out, then holding Shift: its displays take their place.
        var sh = Open(ds);
        sh.Move(At(sh, 1), 1000);
        sh.Tick(1000 + LauncherSession.ClickDwellMs + 1);
        Check.True(sh.Recents == RevitNode, "files out");
        sh.Tick(1000 + LauncherSession.ClickDwellMs + 41, shift: true);
        Check.True(sh.Selector == RevitNode && sh.Recents == null, "Shift: the display picker instead");

        // Right-click a recent file: choose its display.
        var q = Open(ds);
        q.Move(At(q, 1), 1000);
        q.Tick(1000 + LauncherSession.ClickDwellMs + 1);
        var file = q.Scene.RecentRows(RevitNode)[0].Center;
        q.SecondaryClick(file);
        Check.True(q.Selector == RevitNode.WithFile(0) && q.Recents == RevitNode, "right-click a file: its display picker, the files stay");
        var fileTile = q.Scene.TilesFor(RevitNode.WithFile(0))[1];
        Check.True(q.Scene.Extent.Contains(q.Scene.SelectorFor(RevitNode.WithFile(0))), "that picker is inside the launcher");
        var onLeft = Click(q, fileTile.Center, 1500);
        Check.True(onLeft.Launch is { Display: 1 } && onLeft.Launch.Entry.Document == RevitFiles[0], "the file opens on that display");

        // A group: clicking it puts an open card away.
        var g = Open(ds);
        g.Move(At(g, 1), 1000);
        g.Tick(1000 + LauncherSession.ClickDwellMs + 1);
        Click(g, At(g, 0), 1700);
        Check.True(g.Recents == null && g.OpenGroup == 0, "clicking a group: its shortcuts, Revit's files put away");

        // Clicking the empty space around: closes, as before.
        var o = Open(ds);
        o.Move(At(o, 1), 1000);
        o.Tick(1000 + LauncherSession.ClickDwellMs + 1);
        var outside = new PxPoint(o.Scene.Extent.X + 2, o.Scene.Extent.Y + 2);
        Check.Equal(Outcome.Close, Click(o, outside, 1700).Outcome, "clicking outside closes");

        // UI Automation's Invoke on a file (Narrator): like clicking it.
        var u = Open(ds);
        u.Move(At(u, 1), 1000);
        u.Tick(1000 + LauncherSession.ClickDwellMs + 1);
        Check.True(u.Choose(RevitNode.WithFile(3)).Launch?.Entry.Document == RevitFiles[3], "invoked: it opens");
    }

    private static void Keyboard()
    {
        var ds = new[] { Main, Left };
        var s = Open(ds);
        s.Key(LauncherKey.Next);
        s.Key(LauncherKey.Next);
        Check.Equal(new Hit(HitKind.Item, RevitNode), s.Highlight, "Revit highlighted");
        s.Key(LauncherKey.Recents);
        Check.True(s.Recents == RevitNode && s.Highlight == new Hit(HitKind.File, RevitNode.WithFile(0)), "R: its recent files, the first one highlighted");
        s.Key(LauncherKey.Next);
        s.Key(LauncherKey.Next);
        Check.Equal(new Hit(HitKind.File, RevitNode.WithFile(2)), s.Highlight, "arrows move down the files");
        s.Key(LauncherKey.Previous);
        s.Key(LauncherKey.Previous);
        s.Key(LauncherKey.Previous);
        Check.Equal(new Hit(HitKind.File, RevitNode.WithFile(7)), s.Highlight, "and round");
        s.Key(LauncherKey.PickDisplay);
        Check.True(s.Selector == RevitNode.WithFile(7) && s.Highlight.Kind == HitKind.Display, "M: a display for that file");
        s.Key(LauncherKey.Escape);
        Check.True(s.Selector == null && s.Highlight == new Hit(HitKind.File, RevitNode.WithFile(7)), "Esc: back to the file");
        s.Key(LauncherKey.Escape);
        Check.True(s.Recents == null && s.Highlight == new Hit(HitKind.Item, RevitNode), "Esc: back to Revit");
        s.Key(LauncherKey.Recents);
        s.Key(LauncherKey.Recents);
        Check.True(s.Recents == null && s.Highlight == new Hit(HitKind.Item, RevitNode), "R again: back to Revit");
        s.Key(LauncherKey.Recents);
        s.Key(LauncherKey.Next);
        var r = s.Key(LauncherKey.Activate);
        Check.True(r.Outcome == Outcome.Launch && r.Launch!.Entry.Document == RevitFiles[1], "Enter opens the highlighted file");

        var notes = Open(ds);
        for (int i = 0; i < 6; i++) notes.Key(LauncherKey.Next);
        Check.Equal(new Hit(HitKind.Item, new NodeRef(5)), notes.Highlight, "Notes highlighted");
        notes.Key(LauncherKey.Recents);
        Check.True(notes.Recents == null && notes.Message == "No recent files for Notes." && !notes.IsWarning, "R on an app with none says so, calmly");
        var code = Open(ds);
        for (int i = 0; i < 4; i++) code.Key(LauncherKey.Next);
        code.Key(LauncherKey.Recents);
        Check.True(code.Recents == null && code.Message?.StartsWith("Looking for", StringComparison.Ordinal) == true, "R while they're read: says it's looking");
        var web = Open(ds);
        for (int i = 0; i < 3; i++) web.Key(LauncherKey.Next);
        Check.Equal(SessionResult.Nothing, web.Key(LauncherKey.Recents), "R on a website: nothing");

        // Shown by resting the pointer, then the keys: moving on to the next shortcut puts them away.
        var away = Open(ds);
        away.Move(At(away, 1), 1000);
        away.Tick(1000 + LauncherSession.ClickDwellMs + 1);
        Check.True(away.Recents == RevitNode, "shown by a rest");
        away.Key(LauncherKey.Next);
        Check.True(away.Recents == null && away.Highlight == new Hit(HitKind.Item, new NodeRef(2)), "the next shortcut: put away");
        var digit = Open(ds);
        digit.Key(LauncherKey.Next);
        digit.Key(LauncherKey.Next);
        digit.Key(LauncherKey.Recents);
        Check.True(digit.Key(LauncherKey.Digit, 4).Launch?.Entry.Label == "Code", "a digit still opens its position");
    }

