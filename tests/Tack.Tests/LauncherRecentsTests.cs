            "      \"launch\": \"normal\"",
            "    },",
            "    null,",
            "    {",
            "      \"id\": \"projects\",",
            "      \"label\": \"Projects\",",
            "      \"kind\": \"group\",",
            "      \"target\": \"\",",
            "      \"launch\": \"normal\",",
