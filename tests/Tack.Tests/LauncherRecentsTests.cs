    private static void PickOrder()
    {
        var there = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { @"C:\a\1.rvt", @"C:\a\2.rvt", @"C:\a\3.rvt", @"C:\b\4.rvt" };
        int laterRead = 0;
        IEnumerable<string?> Later()
        {
            laterRead++;
            yield return @"C:\b\4.rvt";
        }
        var picked = RecentFiles.Pick(
            [new[] { @"C:\a\1.rvt", @"C:\gone\x.rvt", @"c:\A\1.RVT", null, "cld://x.rvt", @"C:\a\2.rvt" }, new[] { @"C:\a\2.rvt", @"C:\a\3.rvt" }, Later()],
            there.Contains);
        Check.Sequence([@"C:\a\1.rvt", @"C:\a\2.rvt", @"C:\a\3.rvt", @"C:\b\4.rvt"], picked.Select(f => f.Path).ToList(),
            "first list first, a missing file and a duplicate (any case) skipped, then the next lists");
        Check.Equal(1, laterRead, "the last list was needed and read");

        var many = Enumerable.Range(1, 20).Select(i => $@"C:\m\{i}.dwg").ToList();
        laterRead = 0;
        var eight = RecentFiles.Pick([many, Later()], _ => true);
        Check.Equal(RecentFiles.Max, eight.Count, "at most eight");
        Check.Equal(0, laterRead, "a list after enough were found is never read");
        Check.Equal(@"C:\m\8.dwg", eight[^1].Path, "in order");

        var f = new RecentFile(@"D:\Projects\R06 Harbour\Models\R06-ARC-Central.rvt");
        Check.Equal("R06-ARC-Central", f.Stem, "stem");
        Check.Equal(".rvt", f.Extension, "extension");
        Check.Equal(@"D:\Projects\R06 Harbour\Models", f.Folder, "folder");
        Check.Equal(@"D:\Projects", RecentFiles.ShortFolder(@"D:\Projects"), "a short folder as it is");
        string shortened = RecentFiles.ShortFolder(@"D:\Clients\Harbour Health\2026 Hospital Extension\Stage 4\BIM\Models\ARC");
        Check.True(shortened.StartsWith(@"D:\…\", StringComparison.Ordinal) && shortened.EndsWith(@"\Models\ARC", StringComparison.Ordinal) && shortened.Length <= 46,
            $"a long one keeps its drive and its end ({shortened})");
        string unc = RecentFiles.ShortFolder(@"\\fileserver\projects\Harbour Health\2026 Hospital Extension\Stage 4\BIM\ARC");
        Check.True(unc.StartsWith(@"\\fileserver\projects\…\", StringComparison.Ordinal) && unc.EndsWith(@"\ARC", StringComparison.Ordinal), $"a network one keeps its share ({unc})");
        Check.True(RecentFiles.ShortFolder(@"C:\" + new string('x', 120)).Length <= 60, "one very long name is cut");
    }

