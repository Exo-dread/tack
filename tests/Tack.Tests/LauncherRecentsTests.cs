    private static PxPoint At(LauncherSession s, int slot, int child = -1) => s.Scene.CenterOf(new NodeRef(slot, child));

    private static PxPoint Toward(PxPoint from, PxPoint to, double fraction) =>
        new(from.X + (to.X - from.X) * fraction, from.Y + (to.Y - from.Y) * fraction);

    private static long _t;

    /// <summary>Shift+press on the orb and drag along a path; returns the time of the last move.</summary>
    private static long Drag(LauncherSession s, params PxPoint[] path)
    {
        var from = s.Scene.Orb;
        _t = 0;
        s.Begin(from, _t);
        foreach (var to in path)
        {
            for (int i = 1; i <= 6; i++) s.Move(Toward(from, to, i / 6.0), _t += 16);
            from = to;
        }
        return _t;
    }

    /// <summary>Carry on a gesture from where it is.</summary>
    private static long DragOn(LauncherSession s, PxPoint from, PxPoint to)
    {
        for (int i = 1; i <= 8; i++) s.Move(Toward(from, to, i / 8.0), _t += 16);
        return _t;
    }

    private static long Rest(LauncherSession s, long ms, bool shift = false)
    {
        for (long end = _t + ms; _t < end;) s.Tick(_t += 40, shift);
        return _t;
    }

