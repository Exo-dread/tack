        public IFileProbe Probe => Files;
        public IRegistryView Registry => Reg;
        public string RoamingAppData => @"C:\Users\Ra\AppData\Roaming";
        public IReadOnlyList<string> SystemFolders => [@"C:\Windows\System32", @"C:\Windows"];

        public IReadOnlyList<string> AppIdsFor(string program, Shortcut app) =>
            AppIds.Candidates(program, app.Label, Apps, Aliases.TryGetValue(WinPath.FileName(program), out var a) ? a : null, Known);

        public IEnumerable<string> JumpList(string appId)
        {
            ListsRead.Add(appId);
            return Lists.TryGetValue(appId, out var l) ? l : [];
        }

        public string? ReadText(string path) => Texts.TryGetValue(path, out var t) ? t : null;
        // Like the real one: a network path is never asked about.
        public bool Exists(string path) => WinPath.IsUnc(path) || Files.Files.Contains(path);

        public FakeSystem With(params string[] existing)
        {
            foreach (var f in existing) Files.Files.Add(f);
            return this;
        }
    }

