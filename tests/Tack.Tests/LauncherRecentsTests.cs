        // Revit writes UTF-16 with a byte-order mark; others write UTF-8 or nothing.
        string sample = RevitIniText(@"D:\Ø\Model.rvt");
        foreach (var (what, bytes) in new[]
        {
            ("UTF-16 with BOM", Encoding.Unicode.GetPreamble().Concat(Encoding.Unicode.GetBytes(sample)).ToArray()),
            ("UTF-16 without BOM", Encoding.Unicode.GetBytes(sample)),
            ("UTF-8 with BOM", Encoding.UTF8.GetPreamble().Concat(Encoding.UTF8.GetBytes(sample)).ToArray()),
            ("UTF-8", Encoding.UTF8.GetBytes(sample)),
            ("UTF-16 big-endian", Encoding.BigEndianUnicode.GetPreamble().Concat(Encoding.BigEndianUnicode.GetBytes(sample)).ToArray()),
        })
            Check.Sequence([@"D:\Ø\Model.rvt"], AppMru.RevitIni(RecentFiles.Decode(bytes)), what);
        Check.Equal("", RecentFiles.Decode([]), "empty");
    }

