    /// <summary>A fake registry: keys by hive and path, each with named values.</summary>
    private sealed class FakeRegistry : IRegistryView
    {
        private readonly Dictionary<string, Dictionary<string, object>> _keys = new(StringComparer.OrdinalIgnoreCase);

        private static string K(RegHive hive, string path) => hive + "\\" + path.Trim('\\');

        public FakeRegistry Set(RegHive hive, string path, string name, object value)
        {
            // Every parent exists too, as in the real registry.
            var parts = path.Trim('\\').Split('\\');
            for (int i = 1; i <= parts.Length; i++)
            {
                string k = K(hive, string.Join('\\', parts.Take(i)));
                if (!_keys.ContainsKey(k)) _keys[k] = new Dictionary<string, object>(StringComparer.OrdinalIgnoreCase);
            }
            _keys[K(hive, path)][name] = value;
            return this;
        }

        public IReadOnlyList<string> SubKeys(RegHive hive, string path)
        {
            string prefix = K(hive, path) + "\\";
            return _keys.Keys.Where(k => k.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
                .Select(k => k[prefix.Length..].Split('\\')[0]).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        }

        public IReadOnlyList<string> ValueNames(RegHive hive, string path) =>
            _keys.TryGetValue(K(hive, path), out var values) ? values.Keys.ToList() : [];

        public object? Value(RegHive hive, string path, string name) =>
            _keys.TryGetValue(K(hive, path), out var values) && values.TryGetValue(name, out var v) ? v : null;
    }

    private sealed class FakeFiles : IFileProbe
    {
        public readonly HashSet<string> Files = new(StringComparer.OrdinalIgnoreCase);
        public readonly Dictionary<string, string> Handlers = new(StringComparer.OrdinalIgnoreCase);
        public bool FileExists(string path) => Files.Contains(path);
        public bool DirectoryExists(string path) => false;
        public string ExpandEnvironment(string path) => path.Replace("%ProgramFiles%", @"C:\Program Files", StringComparison.OrdinalIgnoreCase);
        public string? DefaultProgramFor(string document) => Handlers.TryGetValue(WinPath.Extension(document), out var h) ? h : null;
    }

    /// <summary>This PC's sources as fixtures: Start menu apps, Jump Lists by app ID, ini files, the registry, files.</summary>
