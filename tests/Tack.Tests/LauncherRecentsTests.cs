    private static void CardPlacement()
    {
        var spots = new (string Name, Display On, PxPoint Orb)[]
        {
            ("main, centre", Main, new PxPoint(1280, 690)),
            ("main, right edge", Main, new PxPoint(2560 - 37.5, 500)),
            ("main, left edge", Main, new PxPoint(37.5, 690)),
            ("main, top-right corner", Main, new PxPoint(2560 - 37.5, 37.5)),
            ("main, bottom-left corner", Main, new PxPoint(37.5, 1380 - 37.5)),
            ("main, bottom edge", Main, new PxPoint(1280, 1380 - 37.5)),
            ("main, top edge", Main, new PxPoint(1280, 37.5)),
            ("left, right edge", Left, new PxPoint(-30, 700)),
            ("left, bottom-left corner", Left, new PxPoint(-1920 + 30, 240 + 1032 - 30)),
            ("left, top edge", Left, new PxPoint(-960, 240 + 30)),
        };
        var problems = new List<string>();
        foreach (var (name, on, orb) in spots)
        {
            var s = Session(orb: orb, displays: [on, on == Main ? Left : Main]);
            s.SetRecents(new NodeRef(3), Files(RevitFiles.Take(5)));
            foreach (var owner in new[] { new NodeRef(1), new NodeRef(3), new NodeRef(0, 0) })
            {
                var box = s.Scene.RecentsBox(owner);
                var area = on.Work.Deflate(LauncherMetrics.EdgeMargin * on.Scale - 0.5);
                if (!area.Contains(box)) problems.Add($"{name} {owner}: off screen ({box})");
                if (!s.Scene.Extent.Contains(box)) problems.Add($"{name} {owner}: outside the launcher window");
                var orbRect = PxRect.Around(orb, s.Scene.OrbRadius, s.Scene.OrbRadius);
                if (box.OverlapArea(orbRect) > 0) problems.Add($"{name} {owner}: covers the orb");
                var item = PxRect.Around(s.Scene.CenterOf(owner), s.Scene.ItemRadius, s.Scene.ItemRadius);
                if (box.OverlapArea(item) > item.Width * item.Height * 0.05) problems.Add($"{name} {owner}: covers its app");
                foreach (var row in s.Scene.RecentRows(owner))
                    if (!box.Contains(row)) problems.Add($"{name} {owner}: a row outside its card");
                Check.Equal(s.Scene.RecentsOf(owner)!.Count, s.Scene.RecentRows(owner).Count, $"{name} {owner}: a row per file");
            }
            // Every file can be reached in one drag from its app.
            var reach = Session(orb: orb, displays: [on]);
            Drag(reach, reach.Scene.CenterOf(RevitNode));
            Rest(reach, LauncherSession.GestureDwellMs + 40);
            if (reach.Recents != RevitNode) { problems.Add($"{name}: Revit's files didn't fan out"); continue; }
            for (int i = 0; i < RevitFiles.Length; i++)
            {
                var r = Session(orb: orb, displays: [on]);
                Drag(r, r.Scene.CenterOf(RevitNode));
                Rest(r, LauncherSession.GestureDwellMs + 40);
                var target = r.Scene.RecentRows(RevitNode)[i].Center;
                DragOn(r, r.Scene.CenterOf(RevitNode), target);
                var result = r.Release(target, _t + 16);
                if (result.Launch?.Entry.Document != RevitFiles[i]) problems.Add($"{name}: file {i + 1} not reached in one drag ({result.Outcome})");
            }
        }
        Check.True(problems.Count == 0, "the card is placed well everywhere:\n" + string.Join("\n", problems));
    }
