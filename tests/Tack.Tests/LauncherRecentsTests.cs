            "}",
        ];
        byte[] written161 = Encoding.UTF8.GetBytes(string.Join(nl, lines));
        var config = LauncherConfigFile.Parse(written161)!;
        Check.True(!config.RecentFiles && config.Slots.Count(s => s != null) == 2, "read as 1.6.1 wrote it");
        byte[] again = LauncherConfigFile.Serialize(config);
        Check.True(again.AsSpan().SequenceEqual(written161), "written back byte for byte:\n" + Encoding.UTF8.GetString(again));
        config.RecentFiles = true;
        Check.True(Encoding.UTF8.GetString(LauncherConfigFile.Serialize(config)).Contains("\"recentFiles\": true"), "turned on, it's written");
    }

    private static void OffByDefault()
    {
        var c = LauncherConfig.CreateDefault();
        Check.True(!c.RecentFiles, "off by default");
        var on = LauncherConfigFile.Parse(Encoding.UTF8.GetBytes("""{ "enabled": true, "recentFiles": true, "slots": [] }"""))!;
        Check.True(on.RecentFiles, "read from launcher.json");
        string json = Encoding.UTF8.GetString(LauncherConfigFile.Serialize(on));
        Check.True(json.Contains("\"recentFiles\": true"), "written to launcher.json");
        var old = LauncherConfigFile.Parse(Encoding.UTF8.GetBytes("""{ "enabled": true, "slots": [ { "kind": "app", "target": "notepad.exe" } ] }"""))!;
        Check.True(!old.RecentFiles, "a launcher.json from 1.6 has it off");
        var stand = new Shortcut { Kind = "app", Target = "x.exe", Document = @"C:\a.txt" };
        Check.True(!Encoding.UTF8.GetString(LauncherConfigFile.Serialize(new LauncherConfig { Slots = [stand] }.Normalize())).Contains("document", StringComparison.OrdinalIgnoreCase),
            "a recent file's path is never written to launcher.json");

        // Off, nothing about the launcher changes: no app offers recent files, and the window is as large as before.
        var scene = LauncherScene.Build(SessionConfig(recents: false), new PxPoint(1280, 700), Main.Work, Main.Scale, [Main], _ => null);
        Check.True(scene.AllNodes().All(n => !scene.MayHaveRecents(n)), "off: no app has recent files");
        var onScene = LauncherScene.Build(SessionConfig(recents: true), new PxPoint(1280, 700), Main.Work, Main.Scale, [Main], _ => null);
        Check.True(onScene.MayHaveRecents(new NodeRef(1)) && !onScene.MayHaveRecents(new NodeRef(2)) && !onScene.MayHaveRecents(new NodeRef(4)),
            "on: apps (.exe) do, websites and folders don't");
        Check.True(onScene.Extent.Contains(scene.Extent), "on, the window has room for a card as well");
    }

