    private static byte[] AliasData(params string[] strings)
    {
        var payload = new List<byte>();
        payload.AddRange(BitConverter.GetBytes(3u)); // version
        foreach (var s in strings) { payload.AddRange(Encoding.Unicode.GetBytes(s)); payload.AddRange([0, 0]); }
        var data = new List<byte>();
        data.AddRange(BitConverter.GetBytes(0x8000001Bu));
        data.AddRange(BitConverter.GetBytes((ushort)payload.Count));
        data.AddRange(BitConverter.GetBytes((ushort)0));
        data.AddRange(payload);
        return data.ToArray();
    }

