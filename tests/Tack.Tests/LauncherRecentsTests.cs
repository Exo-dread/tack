    private static string RevitIniText(params string[] files)
    {
        var sb = new StringBuilder("[Directories]\r\nProjectPath=C:\\Users\\Ra\\Documents\r\n[Recent File List]\r\n");
        // Revit writes them out of order (File15, File16, File1, …): the numbers decide.
        for (int i = files.Length - 1; i >= 0; i--) sb.Append($"File{i + 1}={files[i]}\r\n");
        sb.Append("[Recent Workset List]\r\nConfig4=Custom=b351d963\r\n");
        return sb.ToString();
    }

